"""Compile checked-in built-in Jinja templates into standalone renderers.

Jinja is used here as a lexer/parser only.  The resulting package has no Jinja
or MarkupSafe imports and is safe to use before the lazy Jinja import path.
"""

from __future__ import annotations

import argparse
import ast
import subprocess
import sys
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Iterable

ROOT = Path(__file__).resolve().parents[1]
for import_path in (ROOT, ROOT / "src"):
    if str(import_path) not in sys.path:
        sys.path.insert(0, str(import_path))

from scripts._template_compiler import (  # noqa: E402
    build_environment,
    compile_template,
    inventory_templates,
    iter_template_paths,
)
from scripts._template_compiler.compiler import module_name_for_path  # noqa: E402

TEMPLATE_DIR = ROOT / "src/datamodel_code_generator/model/template"
OUTPUT_DIR = ROOT / "src/datamodel_code_generator/model/_compiled_templates"


def _render_registry(template_paths: Iterable[Path]) -> str:
    entries = tuple(sorted(template_paths))
    mapping = [f"    {path.as_posix()!r}: '.{module_name_for_path(path)}'," for path in entries]
    return (
        "\n".join([
            "# Generated by scripts/compile_builtin_templates.py; do not edit directly.",
            "from __future__ import annotations",
            "",
            "from collections.abc import Callable",
            "from functools import lru_cache",
            "from importlib import import_module",
            "from os import PathLike",
            "",
            "_RENDERER_MODULES: dict[str, str] = {",
            *mapping,
            "}",
            "",
            "",
            "@lru_cache",
            "def _load_renderer(module_name: str) -> Callable[..., str]:",
            "    return import_module(module_name, __package__).render",
            "",
            "",
            "def get_builtin_renderer(template_path: str | PathLike[str]) -> Callable[..., str] | None:",
            '    """Return a generated renderer for an exact built-in relative path."""',
            "    if (module_name := _RENDERER_MODULES.get(str(template_path).replace('\\\\', '/'))) is None:",
            "        return None",
            "    return _load_renderer(module_name)",
        ])
        + "\n"
    )


def _render_init() -> str:
    return "\n".join([  # noqa: FLY002
        '"""Generated standalone renderers for built-in model templates."""',
        "",
        "from .registry import get_builtin_renderer",
        "",
        '__all__ = ["get_builtin_renderer"]',
        "",
    ])


def generated_sources() -> dict[Path, str]:
    """Generate and validate all standalone renderer source files in memory."""
    environment = build_environment()
    inventory_templates(TEMPLATE_DIR, environment)
    template_paths = tuple(path.relative_to(TEMPLATE_DIR) for path in iter_template_paths(TEMPLATE_DIR))
    sources = {}
    for path in template_paths:
        output_path = OUTPUT_DIR / f"{module_name_for_path(path)}.py"
        sources[output_path] = _format_python(compile_template(TEMPLATE_DIR, path, environment), output_path)
    sources[OUTPUT_DIR / "registry.py"] = _format_python(_render_registry(template_paths), OUTPUT_DIR / "registry.py")
    sources[OUTPUT_DIR / "__init__.py"] = _format_python(_render_init(), OUTPUT_DIR / "__init__.py")
    for path, source in sources.items():
        _validate_source(source, path)
    return sources


def _validate_source(source: str, path: Path) -> None:
    """Validate generated Python before writing it to the repository."""
    try:
        ast.parse(source, filename=str(path), feature_version=(3, 10))
    except SyntaxError as error:  # pragma: no cover - protects generated output
        error_message = f"generated invalid Python for {path}: {error}"
        raise RuntimeError(error_message) from error


def _format_python(source: str, path: Path) -> str:
    """Apply the repository formatter while source is still in memory."""
    result = subprocess.run(
        ["ruff", "format", "--stdin-filename", str(path), "-"],
        check=True,
        capture_output=True,
        input=source,
        text=True,
    )
    return result.stdout


def _stale_paths(sources: dict[Path, str]) -> list[Path]:
    stale = [
        path for path, source in sources.items() if not path.is_file() or path.read_text(encoding="utf-8") != source
    ]
    generated_names = {path.name for path in sources}
    stale.extend(path for path in OUTPUT_DIR.glob("*.py") if path.name not in generated_names)
    return sorted(set(stale))


def main(argv: list[str] | None = None) -> int:
    """Generate renderers or report files that differ from generated output."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated template renderers are stale")
    parser.add_argument("--inventory", action="store_true", help="validate the current template feature subset")
    args = parser.parse_args(argv)
    sources = generated_sources()
    if args.inventory:
        print(f"validated {len(sources) - 2} built-in templates")
    if (stale := _stale_paths(sources)) and args.check:
        for path in stale:
            print(path.relative_to(ROOT), file=sys.stderr)
        return 1
    if args.check:
        return 0
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, source in sources.items():
        path.write_text(source, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
